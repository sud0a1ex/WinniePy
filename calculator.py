from winniepy import *

app = Window("WinniePy Calculator 1.0", 300, 400)

tb1 = app.add_textbox()
tb1.place(20, 20)

def edit(txt:str):
  if txt == "clear": tb1.text("")
  elif txt == "equal": tb1.text(eval(tb1.text()))
  else: tb1.text(tb1.text()+txt)

btn_c = app.add_button("C")
btn_c.place(20, 50)
btn_c.on_click(lambda: edit("clear"))

